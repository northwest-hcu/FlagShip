test("keeps empty content frames and rejects incompatible components", async ({ page }) => {
  await add(page, "ボタン"); await add(page, "コンテナ");
  const contentSlot = page.locator('[data-slot-owner="button-1"][data-slot-key="contents"]');
  const heading = contentSlot.locator("> .slot-heading");
  await expect(page.locator('#tree-panel [data-field-key]')).toHaveCount(0);
  await tree(page, "button-1:text").click();
  await page.getByRole("button", { name: "選択したオブジェクトを削除", exact: true }).click();
  await expect(contentSlot).toContainText("Empty slot");
  await tree(page, "container-2").dragTo(heading);
  await expect(object(page, "container-2")).toBeVisible();
  await expect(contentSlot).toContainText("Empty slot");
  await page.locator('[data-library-kind="image"]').dragTo(heading);
  await expect(contentSlot.locator('[data-tree-node="image-3"]')).toBeVisible();
  await tree(page, "image-3").dragTo(page.getByRole("button", { name: "Overlay slot", exact: true }));
  await expect(object(page, "image-3")).toBeVisible();
  await page.getByRole("button", { name: "Context slot", exact: true }).click();
  await expect(contentSlot).toContainText("Empty slot");
});

test("adds Pages, edits path only on Page selection, and keeps page slots independent", async ({ page }) => {
  await add(page, "ボタン");
  await page.getByRole("button", { name: "ページを追加", exact: true }).click();
  await expect(page.locator("[data-page-id]")).toHaveCount(2);
  await expect(object(page, "button-1")).toHaveCount(0);
  await expect(details(page)).toHaveCount(0);
  await page.getByRole("button", { name: "Page Com 02", exact: true }).click();
  await openFields(page, "path");
  await details(page).getByLabel("Path", { exact: true }).fill("/settings");
  await expect(page.locator('[data-page-id="page-2"] .page-path')).toHaveText("/settings");
  const second = page.locator('[data-page-id="page-2"]');
  await second.getByRole("button", { name: "Overlay slot", exact: true }).click();
  await expect(details(page)).toHaveCount(0);
  await add(page, "アイコン");
  const first = page.locator('[data-page-id="page-1"]');
  await first.getByRole("button", { name: "Context slot", exact: true }).click();
  await expect(object(page, "button-1")).toBeVisible();
  await expect(object(page, "icon-2")).toHaveCount(0);
  await tree(page, "button-1").dragTo(second.getByRole("button", { name: "Context slot", exact: true }));
  await expect(object(page, "button-1")).toBeVisible();
  await first.getByRole("button", { name: "Context slot", exact: true }).click();
  await expect(object(page, "button-1")).toHaveCount(0);
  await second.getByRole("button", { name: "Overlay slot", exact: true }).click();
  await expect(object(page, "icon-2")).toBeVisible();
  await page.getByRole("button", { name: "Preview", exact: true }).click();
  await expect(object(page, "button-1")).toBeVisible();
  await expect(object(page, "icon-2")).toBeVisible();
});
